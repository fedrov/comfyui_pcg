"""
Image -> geometry. How the image the AI generated gets back onto the geometry.

Up to this batch the whole chain was **one-way**: geometry -> rasterize -> Control Image ->
diffusion model. The reverse half had only one entry point, Heightfield from Image, and it can only do heightfields.
This file adds the general route -- any image (from a sampler, from a texture library, generated by COPs
themselves) can become point attributes, displacement, or scatter density via uv.

    attribute_from_map   sample by uv -> point / vertex / primitive attributes (Cd, pscale, density...)
    displace_from_map    sample by uv -> push points along the normal (displacement)
    scatter_from_map     scatter points using the image as a density field (rejection sampling; density precision isn't limited by mesh resolution)

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
uv lives on the **vertex**, not the point -- this one fact determines the structure of the whole file
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Houdini's convention (and this plugin's): uv is a vertex attribute. The reason is **uv seams** --
on a seam one point is shared by two uv islands; it has two uvs, which a point attribute can't hold.

So "sample by uv and write to a point attribute" is itself **ambiguous**, and where it's ambiguous a choice
must be made and documented:

    - target is vertex   use that vertex's uv directly, no ambiguity at all. **Recommended**
    - target is point    take the uv of the point's **first** incident vertex
    - target is prim     take the average uv of all the primitive's vertices (the primitive's center in uv)

Why the point mode takes "the first" rather than "the average": on a seam the two uvs are one at u=0 and one at u=1,
averaging to u=0.5 -- sampling the middle of the texture. That result is **both wrong and silent**, whereas taking
the first is at least the true value on one side of the seam. This module counts how many points have inconsistent incident uvs
and puts it in the returned info, so "why does my result have a dirty ring along the seam" has an answer.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
AI images are **sRGB-encoded**; decode before using them as values
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
The IMAGE a diffusion model outputs is for display (display-referred); the 0.5 grey is physically
0.214 luminance, not 0.5. Fine as a color (downstream encodes it back again), but as soon as it is used as a
**value** -- displacement height, density, pscale -- not decoding pushes the midtones up across the board:

    encoded   0.25    0.50    0.75
    linear    0.0508  0.2140  0.5225

For displacement that's a more than 2x difference, and the "looks about right too" kind of error. The default is none (no change),
but every mode that feeds displace / scatter density says in the node tooltip to enable srgb_to_linear.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Bilinear is **exact** here, so tests can be tight down to floating-point error
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Bilinear interpolation reconstructs any function of the form a + b*u + c*v + d*uv **without error**. So as long as the
image is filled with such a bilinear function, the sampled result should match the analytic value to 1e-6, not "roughly".
This is this module's strongest criterion, and it nails down the v flip too -- flip once too few or too many and f(u,v)=v
samples back as 1-v, an error of O(1) rather than O(1e-6).
"""
from __future__ import annotations

import numpy as np

from .core import Geometry, POINT, VERTEX, PRIM, DETAIL, is_string
from .groups import resolve
from .cop.core import CopImage, DEFAULT_LAYER
from .cop import filters as _flt
from . import scatter as _scat

UV_SOURCES = ("auto", "vertex", "point")
FILTERS = ("bilinear", "closest")
BORDERS = ("clamp", "wrap", "black")
DECODES = ("none", "srgb_to_linear", "linear_to_srgb")
CLASSES = (POINT, VERTEX, PRIM)


# ═══════════════════════════════════════════════════════════════ color encoding
def srgb_decode(a):
    """
    sRGB -> linear. A piecewise function, **not** a 2.2 power -- the dark segment is a straight line.

    Strict inverse of cop.control.srgb_encode (round-trip error < 1e-6). It's written here instead of
    reusing control.py because control belongs to the "render output" semantic layer, while this is the
    "image input"; sharing one function would let a change on either side silently affect the other.
    """
    a = np.asarray(a, np.float64)
    return np.where(a <= 0.04045, a / 12.92,
                    np.power(np.maximum(a + 0.055, 0.0) / 1.055, 2.4))


def srgb_encode(a):
    """Linear -> sRGB. Inverse of the above."""
    a = np.asarray(a, np.float64)
    return np.where(a <= 0.0031308, a * 12.92,
                    1.055 * np.power(np.maximum(a, 0.0), 1 / 2.4) - 0.055)


def apply_decode(a, decode):
    if decode == "srgb_to_linear":
        return srgb_decode(a)
    if decode == "linear_to_srgb":
        return srgb_encode(a)
    return np.asarray(a, np.float64)


# ═══════════════════════════════════════════════════════════════ uv lookup
def _uv2(a):
    """Normalize the uv attribute to (N,2). 1 component: pad v=0; 3 components: drop w."""
    a = np.asarray(a, np.float64)
    if a.ndim == 1:
        a = a[:, None]
    if a.shape[1] == 1:
        return np.concatenate([a, np.zeros((len(a), 1))], 1)
    return a[:, :2]


def _first_vertex_of_point(geo):
    """
    Each point's **first** (lowest-numbered) incident vertex; orphan points get -1.

    Assigning in reverse makes the smallest index write last -- faster than argsort, and needs no stable-sort assumption.
    """
    n = geo.npoints
    first = np.full(n, -1, np.int64)
    vp = np.asarray(geo.vertex_point, np.int64)
    if len(vp):
        first[vp[::-1]] = np.arange(len(vp) - 1, -1, -1, dtype=np.int64)
    return first


def uv_of(geo, cls=POINT, uv_attrib="uv", uv_from="auto"):
    """
    Fetch each element's uv; returns ((N,2) float64, valid mask (N,), seam point count).

    "Seam point count" only means something in point mode: how many points have inconsistent incident vertex uvs.
    It isn't an error, it's **information** -- values at these points necessarily represent only one side of the seam.
    """
    name = str(uv_attrib).strip() or "uv"
    have_v = geo.has(VERTEX, name) and not is_string(geo.get(VERTEX, name))
    have_p = geo.has(POINT, name) and not is_string(geo.get(POINT, name))
    src = uv_from
    if src == "auto":
        src = "vertex" if have_v else "point"
    if src == "vertex" and not have_v:
        if not have_p:
            raise KeyError(
                f"uv attribute '{name}' not found. On vertices: "
                f"{sorted(geo.attribs[VERTEX]) or '(none)'}; on points: "
                f"{sorted(geo.attribs[POINT]) or '(none)'}. "
                f"Connect a UV Project / UV Flatten first.")
        src = "point"
    if src == "point" and not have_p:
        if not have_v:
            raise KeyError(f"uv attribute '{name}' not found.")
        src = "vertex"

    seams = 0
    if src == "point":
        uv = _uv2(geo.get(POINT, name))
        if cls == POINT:
            return uv, np.ones(geo.npoints, bool), 0
        if cls == VERTEX:
            return uv[geo.vertex_point], np.ones(geo.nvertices, bool), 0
        vuv = uv[geo.vertex_point]
    else:
        vuv = _uv2(geo.get(VERTEX, name))
        if cls == VERTEX:
            return vuv, np.ones(geo.nvertices, bool), 0
        if cls == POINT:
            first = _first_vertex_of_point(geo)
            ok = first >= 0
            out = np.zeros((geo.npoints, 2))
            out[ok] = vuv[first[ok]]
            # seam stats: any incident vertex differing from "the first" -> this point is ambiguous
            vp = np.asarray(geo.vertex_point, np.int64)
            if len(vp):
                d = np.abs(vuv - out[vp]).max(1)
                seams = int(np.count_nonzero(
                    np.bincount(vp, weights=(d > 1e-6).astype(np.float64),
                                minlength=geo.npoints) > 0))
            return out, ok, seams

    # cls == PRIM: average uv of all vertices in the primitive
    if geo.nprims == 0:
        return np.zeros((0, 2)), np.zeros(0, bool), 0
    pr = geo.vertex_prim().astype(np.int64)
    sz = np.maximum(geo.prim_sizes().astype(np.float64), 1.0)
    out = np.stack([np.bincount(pr, weights=vuv[:, k], minlength=geo.nprims)
                    for k in range(2)], 1) / sz[:, None]
    return out, np.ones(geo.nprims, bool), 0


# ═══════════════════════════════════════════════════════════════ sampling
def sample_layer(image, uv, layer=DEFAULT_LAYER, border="clamp",
                 filter="bilinear", channels="", decode="none"):
    """
    Look up values on the layer by uv; returns (N,C) float64.

    The closest mode uses floor(u*W), not round -- the same pixel-center convention bilinear uses
    (which cell u*W - 0.5 falls in); both must give the same value at pixel centers.
    """
    if not isinstance(image, CopImage):
        raise TypeError("Needs a COPIMAGE (connect COP Import to convert the IMAGE)")
    a = image.need(layer)
    if not isinstance(a, np.ndarray):          # torch / cuda -> move back to numpy
        a = image.to_device("numpy").need(layer)
    a = np.asarray(a, np.float64)
    uv = np.asarray(uv, np.float64).reshape(-1, 2)
    if not len(uv):
        return np.zeros((0, a.shape[2]))

    if filter == "closest":
        H, W = a.shape[0], a.shape[1]
        x = np.floor(uv[:, 0] * W).astype(np.int64)
        y = np.floor(uv[:, 1] * H).astype(np.int64)
        if border == "wrap":
            x, y = np.mod(x, W), np.mod(y, H)
            r = a[y, x]
        else:
            out = (x < 0) | (x >= W) | (y < 0) | (y >= H)
            r = a[np.clip(y, 0, H - 1), np.clip(x, 0, W - 1)]
            if border == "black":
                r = np.where(out[:, None], 0.0, r)
    else:
        # Use the **exact** (numpy float64) backend, not the default numpy (float32) backend.
        # The inputs here are already a float64 layer and float64 uvs; handing them to the float32
        # op table would silently drop precision internally once -- bilinear's "exact reconstruction" of a bilinear function
        # would fall from 1e-15 to 1e-8. Geometry attributes do end up float32, but precision should be lost at the **output**,
        # not inexplicably once in the middle.
        from .cop import backend as _bk
        r = np.asarray(_flt.sample(a, uv[:, 0], uv[:, 1], border=border,
                                   xp=_bk.EXACT), np.float64)

    sel = parse_channels(channels, r.shape[1])
    if sel is not None:
        r = r[:, sel]
    return apply_decode(r, decode)


def parse_channels(spec, ncomp):
    """"0,2" -> [0,2]; empty string -> None (all). Out of range raises right away instead of silently clamping."""
    s = str(spec).strip()
    if not s:
        return None
    idx = []
    for tok in s.replace(";", ",").split(","):
        tok = tok.strip()
        if not tok:
            continue
        i = int(tok)
        if i < 0:
            i += ncomp
        if not (0 <= i < ncomp):
            raise IndexError(f"Channel {tok} out of range: this layer only has {ncomp} channels")
        idx.append(i)
    return idx or None


# ═══════════════════════════════════════════════════ Attribute from Map
def attribute_from_map(geo, image, layer=DEFAULT_LAYER, cls=POINT,
                       name="Cd", group="", uv_attrib="uv", uv_from="auto",
                       border="clamp", filter="bilinear", channels="",
                       decode="none", scale=1.0, offset=0.0, blend=1.0,
                       uv_scale_u=1.0, uv_scale_v=1.0,
                       uv_offset_u=0.0, uv_offset_v=0.0):
    """
    Sample the layer by uv and write it as an attribute.

    With blend < 1, linearly blend with the attribute's **existing value** (treated as 0 if the attribute doesn't exist). Component counts are
    aligned before blending -- blending a 1-channel mask into a 3-component Cd broadcasts the missing components,
    the only interpretation that makes sense.

    uv_scale / uv_offset act on uv before sampling (tiling). They're here rather than making the user connect
    a UV Transform first because "tile the same texture 4 times" is so common.
    """
    if geo is None:
        return Geometry(), {}
    cls = cls if cls in CLASSES else POINT
    out = geo.copy()
    uv, valid, seams = uv_of(geo, cls, uv_attrib, uv_from)
    n = len(uv)
    if n == 0:
        return out, {"count": 0, "seam_points": 0}

    uv = uv * np.array([float(uv_scale_u), float(uv_scale_v)]) \
        + np.array([float(uv_offset_u), float(uv_offset_v)])
    val = sample_layer(image, uv, layer, border, filter, channels, decode)
    val = val * float(scale) + float(offset)
    val[~valid] = 0.0

    nm = str(name).strip()
    if not nm:
        raise ValueError("Attribute name must not be empty")

    cur = geo.get(cls, nm)
    b = float(np.clip(blend, 0.0, 1.0))
    if cur is not None and not is_string(cur) and b < 1.0:
        c = np.asarray(cur, np.float64)
        if c.shape[1] != val.shape[1]:           # component counts differ: broadcast the smaller side
            k = max(c.shape[1], val.shape[1])
            c = np.repeat(c, k, 1)[:, :k] if c.shape[1] == 1 else \
                np.pad(c, ((0, 0), (0, k - c.shape[1])))
            val = np.repeat(val, k, 1)[:, :k] if val.shape[1] == 1 else \
                np.pad(val, ((0, 0), (0, k - val.shape[1])))
        val = c + (val - c) * b

    sel = resolve(geo, cls, group)
    if not sel.all():
        base = geo.get(cls, nm)
        if base is not None and not is_string(base) \
                and base.shape[1] == val.shape[1]:
            keep = np.asarray(base, np.float64)
        else:
            keep = np.zeros_like(val)
        val = np.where(sel[:, None], val, keep)

    out.set(cls, nm, val.astype(np.float32), owned=True)
    return out, {"count": int(sel.sum()), "seam_points": seams,
                 "components": int(val.shape[1])}


# ═══════════════════════════════════════════════════ Displace from Map
def displace_from_map(geo, image, layer=DEFAULT_LAYER, channel=0,
                      group="", uv_attrib="uv", uv_from="auto",
                      border="clamp", filter="bilinear", decode="none",
                      amount=1.0, midpoint=0.0, direction="normal",
                      dir_x=0.0, dir_y=1.0, dir_z=0.0,
                      normal_attrib="N", uv_scale_u=1.0, uv_scale_v=1.0,
                      uv_offset_u=0.0, uv_offset_v=0.0):
    """
    Sample a scalar by uv and push points along the normal (or a fixed direction).

    midpoint is the value that "doesn't move": displacement = (sample - midpoint) x amount. For height maps
    0 is usually the lowest point (midpoint=0), while for normal-map-style "0.5 is flat" enter 0.5.

    With direction="normal", point normals are used; without an N attribute, one is computed on the spot from primitive normals (**not** written back to
    the geometry; after displacement the normals are stale anyway -- for new normals connect a Facet / Normal).
    """
    if geo is None or geo.npoints == 0:
        return Geometry() if geo is None else geo.copy()
    uv, valid, seams = uv_of(geo, POINT, uv_attrib, uv_from)
    uv = uv * np.array([float(uv_scale_u), float(uv_scale_v)]) \
        + np.array([float(uv_offset_u), float(uv_offset_v)])
    h = sample_layer(image, uv, layer, border, filter,
                     str(int(channel)), decode)[:, 0]
    h = (h - float(midpoint)) * float(amount)
    h[~valid] = 0.0

    if direction == "normal":
        nm = str(normal_attrib).strip() or "N"
        N = geo.get(POINT, nm)
        if N is None or is_string(N) or N.shape[1] < 3:
            from .peak import point_normals
            N = point_normals(geo)
        N = np.asarray(N, np.float64)[:, :3]
        l = np.linalg.norm(N, axis=1, keepdims=True)
        D = N / np.where(l == 0, 1.0, l)
    else:
        d = np.array([float(dir_x), float(dir_y), float(dir_z)])
        l = np.linalg.norm(d)
        D = np.broadcast_to((d / l if l > 0 else np.array([0.0, 1.0, 0.0])),
                            (geo.npoints, 3))

    sel = resolve(geo, POINT, group)
    P = np.asarray(geo.get(POINT, "P"), np.float64)
    P = P + D * np.where(sel, h, 0.0)[:, None]
    out = geo.copy()
    out.set(POINT, "P", P.astype(np.float32), owned=True)
    return out


# ═══════════════════════════════════════════════════ Scatter from Map
SFM_METHODS = ("count", "density", "coverage")
SFM_VARIABILITY = ("none", "uniform", "normal", "exact")


def scatter_from_map(geo, image, layer=DEFAULT_LAYER, channel=0, group="",
                     count=1000, uv_attrib="uv", border="clamp",
                     filter="bilinear", decode="none",
                     density_scale=1.0, density_floor=0.0, invert=False,
                     oversample=4.0, max_rounds=6, seed=0,
                     relax_iterations=0, out_density="density",
                     uv_scale_u=1.0, uv_scale_v=1.0,
                     uv_offset_u=0.0, uv_offset_v=0.0,
                     scatter_method="count", density=1.0, coverage=0.5,
                     outer_radius=1.0, variability="none", range_min=0.5,
                     range_max=1.5, spread=0.25, exact_scale=1.0,
                     randomize_orients=False, match_normals=True,
                     randomize_up=0.0, randomize_yaw=180.0, max_points=0,
                     quantization=0.0, tag_name=""):
    """
    Scatter points using an image as a density field.

    ━━ Why **rejection sampling**, rather than "write the image as a density point attribute and feed it to Scatter"
    The latter can be wired up in one line (Attribute from Map -> Scatter's Density Attribute),
    and this plugin has both nodes. But its density precision is capped by **mesh resolution**: Scatter's
    density attribute is the average of a triangle's three vertices; a 2x2 grid facing a 1024^2 image
    leaves only 4 numbers for the whole image. Useless for "grow grass by the AI's mask".

    Rejection sampling looks up the image at **each sample point's own uv**: first scatter oversample times as many points uniformly, and keep each point
    with probability density(uv) / max_density. The density's spatial precision is limited only by the image resolution,
    and has nothing to do with how fine the mesh is. The cost is scattering several times more points, and the count isn't exact -- so there's
    a multi-round loop: if short, scatter another round with a different seed; once enough, truncate.

    ━━ The probability upper bound is **the global maximum of the image** (after invert / floor)
    Rejection sampling needs p <= 1, so divide by the maximum. If the image has one isolated bright spot, the
    acceptance rate everywhere else is dragged down by it -- showing up as many rounds of scattering. This is the inherent cost of rejection sampling, not a
    bug; if you hit it, put a COP Blur on the image first or tone down the highlights.

    density_floor gives a minimum density (0-1), so "completely black areas of the image" still get some points.

    ━━ Processing order: decode -> invert -> floor -> scatter; density_scale only multiplies the density attribute written out
    The point count is fixed by count, and the acceptance probability is divided by the whole-image maximum, so multiplying everything by a number **cannot**
    change the distribution -- all it can affect is the density value written out. Before pcg90 scale multiplied ahead of invert / floor:
    1 - 2*d became negative where d > 0.5 and was clamped to 0, and floor was compared against the scaled value,
    so scale "inexplicably" changed the distribution only in combination with invert / floor. Now invert / floor
    both operate on 0-1 image values, and scale is independent of the distribution.
    """
    if geo is None:
        return Geometry()
    if scatter_method not in SFM_METHODS:
        raise ValueError(f"Scatter Method must be one of {SFM_METHODS}")
    if variability not in SFM_VARIABILITY:
        raise ValueError(f"Variability Method must be one of {SFM_VARIABILITY}")
    post = dict(seed=seed, variability=variability, range_min=range_min, range_max=range_max,
                spread=spread, exact_scale=exact_scale, outer_radius=outer_radius,
                randomize_orients=randomize_orients, match_normals=match_normals,
                randomize_up=randomize_up, randomize_yaw=randomize_yaw,
                quantization=quantization, tag_name=tag_name)
    if scatter_method != "count":
        return _post(_scatter_by_density(
            geo, image, layer, channel, group, uv_attrib, border, filter, decode,
            density_scale, density_floor, invert, seed, out_density, uv_scale_u,
            uv_scale_v, uv_offset_u, uv_offset_v, scatter_method, density, coverage,
            outer_radius, variability, range_min, range_max, spread, exact_scale,
            max_points), **post)
    n_target = max(0, int(count))
    if int(max_points) > 0:                    # Max Points: hard cap
        n_target = min(n_target, int(max_points))
    if n_target == 0:
        return Geometry()
    over = max(1.0, float(oversample))
    # ━━ The random stream used for rejection must be **offset** from Scatter's own stream
    # Initially both sides used default_rng(seed). Same seed = same sequence, and the first n numbers Scatter
    # consumes are exactly the ones used to pick triangles (t = searchsorted(cdf, r*total)),
    # so "the i-th point's acceptance test" and "which triangle the i-th point lands in" were fully correlated.
    # The symptom is very subtle: mask tests still all pass (hard boundaries aren't affected by the correlation), but with a density ramp
    # the statistics shift entirely -- the mean of u is 0.600 instead of the analytic 2/3, and worse, **v, which has nothing to do with
    # density**, also shifts to 0.383 (should be 0.5). So the criteria must include "an axis the density doesn't act on",
    # otherwise this kind of bug can't be caught.
    rng = np.random.default_rng(int(seed) ^ 0x5CA77E2)

    # probability upper bound: the maximum of the whole image. Per-point p = d / dmax is then always <= 1.
    a = image.need(layer)
    if not isinstance(a, np.ndarray):
        a = image.to_device("numpy").need(layer)
    ch = int(channel) % int(a.shape[2])
    full = apply_decode(np.asarray(a[:, :, ch], np.float64), decode)
    if invert:
        full = 1.0 - full
    fl = float(np.clip(density_floor, 0.0, 1.0))
    dmax = float(np.max(full)) if full.size else 0.0
    dmax = max(dmax, fl, 1e-12)

    pieces, got = [], 0
    n_try = int(np.ceil(n_target * over))
    for r in range(max(1, int(max_rounds))):
        pts = _scat.scatter(geo, group=group, force_total_count=True,
                            count=n_try, seed=int(seed) + 1 + r * 7919,
                            randomize_order=False,
                            relax_iterations=0,
                            interpolate_attribs=True,
                            interpolate_vertex_attribs=True)
        if pts.npoints == 0:
            break
        uv, valid, _ = uv_of(pts, POINT, uv_attrib, "point")
        uv = uv * np.array([float(uv_scale_u), float(uv_scale_v)]) \
            + np.array([float(uv_offset_u), float(uv_offset_v)])
        d = sample_layer(image, uv, layer, border, filter, str(ch),
                         decode)[:, 0]
        if invert:
            d = 1.0 - d
        d = np.maximum(d, fl)
        p = np.clip(d / dmax, 0.0, 1.0) * valid
        keep = rng.random(len(p)) < p
        idx = np.nonzero(keep)[0]
        if len(idx):
            pieces.append((pts, idx, d[idx] * float(density_scale)))
            got += len(idx)
        if got >= n_target:
            break
        # this round's acceptance rate decides how many to scatter next round -- converges much faster than a fixed multiple
        rate = max(len(idx) / max(1, len(p)), 1e-3)
        n_try = int(np.ceil((n_target - got) / rate * 1.2)) + 16
        n_try = min(n_try, _scat.MAX_POINTS_HARD)

    if not pieces:
        return Geometry()
    out = _concat_points(pieces, out_density)
    if out.npoints > n_target:
        out = _take_points(out, np.arange(n_target))
    if relax_iterations > 0:
        # Relaxation has to be done on the source surface, and handing it to Scatter's machinery isn't worth it; here we only shuffle the order.
        # For blue noise, connect Point Relax downstream -- forcing in a half-baked implementation would be worse.
        pass
    perm = np.random.default_rng(int(seed) ^ 0x5EED).permutation(out.npoints)
    return _post(_take_points(out, perm), **post)


def _mask_full(image, layer, channel, decode, invert):
    a = image.need(layer)
    if not isinstance(a, np.ndarray):
        a = image.to_device("numpy").need(layer)
    ch = int(channel) % int(a.shape[2])
    full = apply_decode(np.asarray(a[:, :, ch], np.float64), decode)
    return (1.0 - full if invert else full), ch


def _e_scale2(variability, range_min, range_max, spread, exact_scale):
    """E[scale^2]. The normal mode approximates by the pre-truncation N(midpoint, Spread): mean^2 + spread^2."""
    a, b = float(range_min), float(range_max)
    if variability == "uniform":
        return (a * a + a * b + b * b) / 3.0
    if variability == "normal":
        return (0.5 * (a + b)) ** 2 + float(spread) ** 2
    if variability == "exact":
        return float(exact_scale) ** 2
    return 1.0


def _scatter_by_density(geo, image, layer, channel, group, uv_attrib, border, filter, decode,
                        density_scale, density_floor, invert, seed, out_density,
                        uv_scale_u, uv_scale_v, uv_offset_u, uv_offset_v, method, density,
                        coverage, outer_radius, variability, range_min, range_max, spread,
                        exact_scale, max_points):
    """
    By Density / By Coverage using Mask Layer: the point count isn't fixed; it follows mask value x density (points per unit area).

    Candidate count = lambda x area x max(mask), each candidate kept with probability mask/max -- the expected count is exactly lambda x integral of mask dA,
    so one round suffices, without Total Count's multi-round top-up.
        density   λ = Density
        coverage  lambda = Coverage / (pi * E[(Outer Radius * scale)^2]): each point occupies a disk of radius
                  Outer Radius x scale, covering the Coverage fraction of the (mask-weighted) area
    """
    from .spatial import tri_soup
    tri = tri_soup(geo, group)[0]
    if not len(tri):
        return Geometry()
    P = np.asarray(geo.get(POINT, "P"), np.float64)
    A, B, C = P[tri[:, 0]], P[tri[:, 1]], P[tri[:, 2]]
    area = 0.5 * float(np.linalg.norm(np.cross(B - A, C - A), axis=1).sum())
    if method == "density":
        lam = float(density)
    else:
        r2 = float(outer_radius) ** 2 * _e_scale2(variability, range_min, range_max, spread,
                                                  exact_scale)
        if not r2 > 0:
            raise ValueError("By Coverage needs Outer Radius x scale > 0")
        lam = float(coverage) / (np.pi * r2)
    full, ch = _mask_full(image, layer, channel, decode, invert)
    fl = float(np.clip(density_floor, 0.0, 1.0))
    dmax = max(float(np.max(full)) if full.size else 0.0, fl, 1e-12)
    n_try = min(int(round(lam * area * dmax)), _scat.MAX_POINTS_HARD)
    if n_try <= 0:
        return Geometry()
    pts = _scat.scatter(geo, group=group, force_total_count=True, count=n_try,
                        seed=int(seed) + 1, randomize_order=False, relax_iterations=0,
                        interpolate_attribs=True, interpolate_vertex_attribs=True)
    if pts.npoints == 0:
        return Geometry()
    uv, valid, _ = uv_of(pts, POINT, uv_attrib, "point")
    uv = uv * np.array([float(uv_scale_u), float(uv_scale_v)]) \
        + np.array([float(uv_offset_u), float(uv_offset_v)])
    d = sample_layer(image, uv, layer, border, filter, str(ch), decode)[:, 0]
    if invert:
        d = 1.0 - d
    d = np.maximum(d, fl)
    rng = np.random.default_rng(int(seed) ^ 0x5CA77E2)    # offset from the triangle-picking stream
    keep = rng.random(len(d)) < np.clip(d / dmax, 0.0, 1.0) * valid
    idx = np.nonzero(keep)[0]
    out = _concat_points([(pts, idx, d[idx] * float(density_scale))], out_density)
    perm = np.random.default_rng(int(seed) ^ 0x5EED).permutation(out.npoints)
    out = _take_points(out, perm)
    if int(max_points) > 0 and out.npoints > int(max_points):
        out = _take_points(out, np.arange(int(max_points)))
    return out


def _post(out, seed, variability, range_min, range_max, spread, exact_scale, outer_radius,
          randomize_orients, match_normals, randomize_up, randomize_yaw, quantization,
          tag_name):
    """
    Variability (pscale + footprint), Randomize Orients (N / orient), Quantization, Tag Name.
    With everything at defaults no attributes are added at all (= old output). Each random stream is independent of the others.
    """
    n = out.npoints
    if n == 0:
        return out
    if variability != "none":
        rng = np.random.default_rng([int(seed) & 0xFFFFFFFF, 0x5CA1E])
        a, b = float(range_min), float(range_max)
        if variability == "uniform":
            sc = rng.uniform(a, b, n)
        elif variability == "normal":
            sc = np.clip(rng.normal(0.5 * (a + b), float(spread), n), min(a, b), max(a, b))
        else:
            sc = np.full(n, float(exact_scale))
        out.set(POINT, "pscale", sc[:, None].astype(np.float32), owned=True)
        out.set(POINT, "footprint", (sc * float(outer_radius))[:, None].astype(np.float32),
                owned=True)
    if randomize_orients:
        from .scatteralign import _rot
        from .curveframe import mat_to_quat
        rng = np.random.default_rng([int(seed) & 0xFFFFFFFF, 0x0A1E])
        if match_normals and out.has(POINT, "N"):
            N = np.asarray(out.get(POINT, "N"), np.float64)
        else:
            N = np.tile([0.0, 1.0, 0.0], (n, 1))
        N = N / np.maximum(np.linalg.norm(N, axis=1, keepdims=True), 1e-300)
        # tangent reference: world +Z projected onto the tangent plane (+X when parallel to N)
        ref = np.where(np.abs(N[:, 2:3]) > 0.9999, [[1.0, 0, 0]], [[0, 0, 1.0]])
        f = ref - N * np.einsum("ij,ij->i", ref, N)[:, None]
        f /= np.maximum(np.linalg.norm(f, axis=1, keepdims=True), 1e-300)
        tdir = rng.random(n) * 2 * np.pi
        tamt = np.radians(float(randomize_up)) * rng.random(n)
        yaw = np.radians(float(randomize_yaw)) * (2 * rng.random(n) - 1)
        if float(randomize_up) != 0:                         # Randomize Up: tilt the normal randomly
            side = np.cross(N, f)
            ax = np.cos(tdir)[:, None] * f + np.sin(tdir)[:, None] * side
            Rt = _rot(ax, tamt)
            N = np.einsum("nij,nj->ni", Rt, N)
            f = np.einsum("nij,nj->ni", Rt, f)
        f = np.einsum("nij,nj->ni", _rot(N, yaw), f)        # Randomize Yaw: rotate around the normal
        x = np.cross(N, f)
        M = np.stack([x, N, f], 2)                           # instance +Y -> normal, +Z -> forward
        out.set(POINT, "N", N.astype(np.float32), owned=True)
        out.set(POINT, "orient", mat_to_quat(M).astype(np.float32), owned=True)
    if float(quantization) > 0:
        q = float(quantization)
        Pq = np.round(np.asarray(out.get(POINT, "P"), np.float64) / q) * q
        out.set(POINT, "P", Pq.astype(out.get(POINT, "P").dtype), owned=True)
    if str(tag_name).strip():
        out.set_string(POINT, "tag", np.full(n, str(tag_name).strip()))
    return out


def _concat_points(pieces, out_density=""):
    """Concatenate the point clouds from several rounds. Attributes are intersected -- each round's attribute set is actually the same."""
    names = None
    for g, idx, _ in pieces:
        s = {k for k, v in g.attribs[POINT].items() if not is_string(v)}
        names = s if names is None else (names & s)
    names = sorted(names or [])
    out = Geometry(sum(len(i) for _, i, _ in pieces))
    for k in names:
        out.set(POINT, k,
                np.concatenate([g.get(POINT, k)[i] for g, i, _ in pieces], 0),
                owned=True)
    nm = str(out_density).strip()
    if nm:
        out.set(POINT, nm,
                np.concatenate([d for _, _, d in pieces])[:, None]
                .astype(np.float32), owned=True)
    return out


def _take_points(geo, idx):
    out = Geometry(len(idx))
    for k, v in geo.attribs[POINT].items():
        out.set(POINT, k, v[idx], owned=True)
    return out
