_VEC_ALLOWED = {
    "direction_length": ("set_always", "set_initial", "set", "add", "subtract",
                         "multiply", "minimum", "maximum"),
    "direction_only": ("add", "subtract", "rotate", "spread", "interpolate"),
    "length_only": ("add", "subtract", "multiply", "minimum", "maximum"),
}


def _unit(v):
    L = np.linalg.norm(v, axis=1, keepdims=True)
    return v / np.where(L < 1e-12, 1.0, L), L[:, 0]


def _vec_attr(geo, cls, nm, what):
    a = geo.get(cls, str(nm or "").strip()) if str(nm or "").strip() else None
    if a is None or is_string(a):
        have = sorted(geo.attribs[cls].keys())
        raise KeyError(f"{what}: {cls} has no numeric attribute '{nm}'. Existing: {have or '(none)'}")
    a = a.astype(np.float64)
    if a.shape[1] == 1:
        return np.repeat(a, 3, axis=1)
    if a.shape[1] != 3:
        raise ValueError(f"{what}: '{nm}' has {a.shape[1]} components, 3 required.")
    return a


def slerp_dirs(a, b, t):
    """Row-wise spherical interpolation of unit vectors. Opposite vectors (180 deg apart) have no unique great circle; falls back to linear then normalize."""
    t = np.asarray(t, np.float64).reshape(-1, 1)
    c = np.clip((a * b).sum(1, keepdims=True), -1.0, 1.0)
    th = np.arccos(c)
    s = np.sin(th)
    ok = s > 1e-6
    wa = np.where(ok, np.sin((1 - t) * th) / np.where(ok, s, 1.0), 1 - t)
    wb = np.where(ok, np.sin(t * th) / np.where(ok, s, 1.0), t)
    return _unit(wa * a + wb * b)[0]


def rotate_about(v, axis, deg):
    """Rodrigues: rotates v about axis (per row, normalized) by deg degrees."""
    k = _unit(axis)[0]
    a = np.radians(np.asarray(deg, np.float64)).reshape(-1, 1)
    return (v * np.cos(a) + np.cross(k, v) * np.sin(a)
            + k * (k * v).sum(1, keepdims=True) * (1 - np.cos(a)))


def _perp(d):
    """Per row, a unit vector perpendicular to d (d already normalized)."""
    a = np.where((np.abs(d[:, 0]) < 0.9)[:, None], [[1.0, 0, 0]], [[0, 1.0, 0]])
    return _unit(np.cross(d, a))[0]


def vector_values(u3, mode, amplitude, amp_scale, vmin, vmax, table_text):
    """
    u3 (N,3) in [0,1] -> adjustment vector. Positive: 0..Amplitude; Zero Centered: first shifted to
    -0.5..0.5, then multiplied by Amplitude (per the docs, so with amplitude 1 it is +/-0.5, not +/-1).
    Specific Values: one vector per line "x y z [w=weight]", picked by weight with the first component's u.
    """
    _check(mode, VEC_RANGES, "Range Values")
    amp = float(amplitude) * np.asarray(amp_scale, np.float64)[None, :]
    if mode == "positive":
        return u3 * amp
    if mode == "zero_centered":
        return (u3 - 0.5) * amp
    if mode == "min_max":
        lo = np.asarray(vmin, np.float64)[None, :]
        hi = np.asarray(vmax, np.float64)[None, :]
        return lo + (hi - lo) * u3
    tab = parse_value_list(table_text)
    for vals, _ in tab:
        if len(vals) != 3:
            raise ValueError(f"Each line of the vector value table needs 3 numbers (x y z); one line has {len(vals)}.")
    idx = pick_specific(u3[:, 0], [(np.array([float(i)]), w)
                                   for i, (_, w) in enumerate(tab)]).astype(np.int64)
    return np.stack([v for v, _ in tab])[idx]


def adjust_vector(geo, name="v", cls=POINT, group="",
                  preprocess=False, overwrite_initial=False, initial_from="constant",
                  initial_vector=(0.0, 1.0, 0.0), initial_attrib="N",
                  reverse=False, pre_unit=False, use_pre_scale=False, pre_scale=1.0,
                  adjust_value=True, adjust_for="direction_length",
                  operation="set_always", adjust_with="constant",
                  constant_vector=(0.0, 1.0, 0.0), vec_range="zero_centered",
                  amplitude=1.0, amp_scale=(1.0, 1.0, 1.0),
                  min_vector=(0.0, 0.0, 0.0), max_vector=(1.0, 1.0, 1.0),
                  vector_list="0 1 0", scalar_value=1.0, scalar=None,
                  axis_from="constant", axis=(0.0, 1.0, 0.0), axis_attrib="up",
                  goal_from="constant", goal=(0.0, 1.0, 0.0), goal_attrib="N",
                  adjust_attrib="",
                  rand_by="element_number", custom_attrib="id", seed=0, noise=None,
                  blend_mode="constant", blend=1.0, blend_attrib="",
                  blend_type="linear", use_post_scale=False, post_scale=1.0,
                  use_min_length=False, min_length=0.0,
                  use_max_length=False, max_length=1.0, post_unit=False,
                  length_attrib="", outlier_attrib=""):
    """
    Attribute Adjust Vector. Adjustment for decides what is changed:

        direction_length  the whole vector; the adjustment value is a vector (the only mode that can change zero vectors)
        direction_only    only the direction, length unchanged: Add / Subtract add a vector then renormalize to the original length;
                          Rotate rotates by Angle degrees about the axis; Spread lands on the cone around the original direction with half-angle Angle
                          (random azimuth); Interpolate spherically interpolates towards Goal by Bias
        length_only       only the length, direction unchanged; the adjustment value is a scalar

    Zero vectors stay zero under direction_only / length_only (per the docs).
    """
    if geo is None:
        return Geometry()
    _check(cls, CLASSES, "Attribute Class")
    _check(adjust_for, ADJUST_FOR, "Adjustment for")
    _check(operation, VEC_OPERATIONS, "Operation")
    _check(adjust_with, PATTERNS, "Adjust With")
    _check(initial_from, INITIAL_FROM, "Initial Value From")
    _check(blend_type, BLEND_TYPES, "Blend Type")
    if adjust_value and operation not in _VEC_ALLOWED[adjust_for]:
        raise ValueError(f"With Adjustment for = {adjust_for}, Operation must be one of "
                         f"{_VEC_ALLOWED[adjust_for]}, got '{operation}'.")
    nm = str(name or "").strip()
    if not nm:
        raise ValueError("Attribute Name is empty.")
    n = geo.count(cls)
    if n == 0:
        return geo.copy()
    cur = geo.get(cls, nm)
    if cur is not None and (is_string(cur) or cur.shape[1] != 3):
        raise ValueError(f"'{nm}' is not a 3-component numeric attribute; Attribute Adjust Vector only handles vectors.")
    existed = cur is not None
    orig = cur.astype(np.float64) if existed else np.zeros((n, 3))
    dt = cur.dtype if existed else np.dtype(np.float32)

    # ── Pre-Process
    base = orig.copy()
    if preprocess:
        if overwrite_initial:
            if initial_from == "constant":
                base = np.tile(np.asarray(initial_vector, np.float64), (n, 1))
            elif initial_from == "attribute":
                base = _vec_attr(geo, cls, initial_attrib, "Initial Value From")
            else:
                from .ops import compute_normals
                gn = compute_normals(geo, cls, name="__aa2_N")
                base = gn.get(cls, "__aa2_N").astype(np.float64)
            existed = True                 # the initial value has been written, so Set Initial no longer overwrites
        if reverse:
            base = -base
        if pre_unit:
            base = _unit(base)[0]
        if use_pre_scale:
            base = base * float(pre_scale)

    sel = resolve(geo, cls, group)
    outl = np.zeros(n, bool)
    out = base
    if adjust_value:
        keys = None
        scalar_op = adjust_for == "length_only" or operation in (
            "rotate", "spread", "interpolate")
        if adjust_with in ("random", "noise"):
            keys = element_keys(geo, cls, rand_by, custom_attrib)
        nz = noise or NoiseSpec()

        if scalar_op:
            if adjust_with == "constant":
                s = np.full(n, float(scalar_value))
            elif adjust_with == "attribute":
                s = _vec_attr(geo, cls, adjust_attrib, "Adjustment Attribute")[:, 0]
            else:
                u = rand_u(keys, seed, 401) if adjust_with == "random" else nz.u(geo, cls, seed, 0)
                s, outl = (scalar or ScalarSpec()).values(u, keys)
        else:
            if adjust_with == "constant":
                adj = np.tile(np.asarray(constant_vector, np.float64), (n, 1))
            elif adjust_with == "attribute":
                adj = _vec_attr(geo, cls, adjust_attrib, "Adjustment Attribute")
            else:
                # Each of the three components uses its own independent random / noise (different salt), otherwise the vector could only lie on the diagonal
                if adjust_with == "random":
                    u3 = np.stack([rand_u(keys, seed, 401 + 17 * c) for c in range(3)], 1)
                else:
                    u3 = np.stack([nz.u(geo, cls, seed, 7919 * c) for c in range(3)], 1)
                adj = vector_values(u3, vec_range, amplitude, amp_scale, min_vector,
                                    max_vector, vector_list)

        d, L = _unit(base)
        if adjust_for == "direction_length":
            op = "set_always" if operation == "set" else operation
            out = combine(op, base, adj, existed)
        elif adjust_for == "length_only":
            newL = combine(operation, L, s, True)
            out = d * newL[:, None]
        else:
            if operation in ("add", "subtract"):
                nd = _unit(base + adj if operation == "add" else base - adj)[0]
            elif operation == "rotate":
                ax = (_vec_attr(geo, cls, axis_attrib, "Axis Attribute") if axis_from == "attribute"
                      else np.tile(np.asarray(axis, np.float64), (n, 1)))
                nd = rotate_about(d, ax, s)
            elif operation == "spread":
                # Random azimuth (the docs don't say how; by element number / custom attribute + Seed, same scheme as Random)
                kk = keys if keys is not None else element_keys(geo, cls, rand_by, custom_attrib)
                phi = 2 * np.pi * rand_u(kk, seed, 977)
                a = np.radians(s)[:, None]
                p = _perp(d)
                q = np.cross(d, p)
                nd = d * np.cos(a) + (p * np.cos(phi)[:, None] + q * np.sin(phi)[:, None]) * np.sin(a)
            else:
                gv = (_vec_attr(geo, cls, goal_attrib, "Goal Attribute") if goal_from == "attribute"
                      else np.tile(np.asarray(goal, np.float64), (n, 1)))
                nd = slerp_dirs(d, _unit(gv)[0], np.clip(s, 0.0, 1.0))
            # Zero vectors: L = 0, so the product is still 0 -- the docs' "zero vectors stay zero" needs no special case
            out = nd * L[:, None]

    # ── Post-Process
    w = blend_weights(geo, cls, n, blend_mode, blend, blend_attrib)
    if blend_type == "linear":
        out = base + (out - base) * w[:, None]
    else:
        # Spherical: direction interpolated spherically, length linearly. If one end is a zero vector _unit gives 0,
        # slerp falls back to the other end's direction and the length is linear -- exactly a linear blend, no special case needed
        d0, L0 = _unit(base)
        d1, L1 = _unit(out)
        out = slerp_dirs(d0, d1, w) * (L0 + (L1 - L0) * w)[:, None]
    if use_post_scale:
        out = out * float(post_scale)
    if use_min_length or use_max_length:
        d, L = _unit(out)
        nl = L
        if use_min_length:
            nl = np.maximum(nl, float(min_length))
        if use_max_length:
            nl = np.minimum(nl, float(max_length))
        # A zero vector has no direction, so a minimum length cannot be enforced: _unit gives a 0 direction and the product stays zero
        out = d * nl[:, None]
    if post_unit:
        out = _unit(out)[0]
    out = np.where(sel[:, None], out, orig)

    g = geo.copy()
    g.set(cls, nm, out.astype(dt), owned=True)
    lnm = str(length_attrib or "").strip()
    if lnm:
        g.set(cls, lnm, np.linalg.norm(out, axis=1).astype(np.float32)[:, None], owned=True)
    onm = str(outlier_attrib or "").strip()
    if onm:
        g.set(cls, onm, (outl & sel).astype(np.int32)[:, None], owned=True)
    return g


# ══════════════════════════════════════════════════════════ Color
COLOR_OPERATIONS = ("set_always", "set_initial", "add", "subtract", "multiply",
                    "overlay", "screen", "hard_mix", "difference", "minimum", "maximum")
COLOR_PATTERNS = ("constant", "random", "noise", "color_attribute",
                  "remap_attribute", "bounding_box")
COLOR_RANGES = ("min_max", "color_ramp", "specific")
COLOR_SPACES = ("rgb", "hsv")
COLOR_SCHEMES = ("custom", "constant", "complementary", "analogous2", "analogous4",
                 "triadic", "tetradic", "shades5", "tints5")
COLOR_INITIAL = ("constant", "color_attribute", "float_attribute")


def _hsv(rgb):
    from .cop.pixel import rgb_to_hsv
    return rgb_to_hsv(np.asarray(rgb, np.float64))


def _rgb(hsv):
    from .cop.pixel import hsv_to_rgb
    return hsv_to_rgb(np.asarray(hsv, np.float64))


def color_scheme(scheme, base, distance=30.0):
    """
    Color Scheme: derives a set of colours from a base colour (in Houdini a menu that "fills a multiparm").
    Hue schemes rotate around the colour wheel by Distance (degrees); Triadic is fixed at +/-120 deg; 5 Shades multiplies the value by
    1, .8, .6, .4, .2 in turn, 5 Tints multiplies the saturation by the same factors (the docs only say "Distance controls
    the spacing" and give no step for Shades / Tints; here it is fixed at 0.2, and Distance only affects hue).
    """
    _check(scheme, COLOR_SCHEMES, "Color Scheme")
    h, s, v = _hsv(np.asarray(base, np.float64).reshape(3))
    d = float(distance) / 360.0
    hues = {"constant": [0], "complementary": [0, .5], "analogous2": [-d, 0, d],
            "analogous4": [-2 * d, -d, 0, d, 2 * d], "triadic": [-1 / 3, 0, 1 / 3],
            "tetradic": [0, d, .5, .5 + d]}
    if scheme in hues:
        return _rgb(np.array([[h + o, s, v] for o in hues[scheme]]))
    k = 1.0 - 0.2 * np.arange(5)
    if scheme == "shades5":
        return _rgb(np.array([[h, s, v * f] for f in k]))
    return _rgb(np.array([[h, s * f, v] for f in k]))


def color_combine(op, a, b, existed):
    """
    Operation (a = original colour, b = adjustment colour, per channel). Overlay / Screen use the common layer blend formulas;
    Overlay splits light/dark by the **original colour** (the docs only say "light and dark parts are treated differently", no formula); Hard Mix
    per the docs: a + b >= 1 gives 1, otherwise 0; Difference per the docs "adjustment value minus original value" = b - a (no absolute value).
    """
    _check(op, COLOR_OPERATIONS, "Operation")
    if op in ("set_always", "set_initial", "add", "subtract", "multiply",
              "minimum", "maximum"):
        return combine(op, a, b, existed)
    if not existed:
        return b
    if op == "screen":
        return 1.0 - (1.0 - a) * (1.0 - b)
    if op == "overlay":
        return np.where(a < 0.5, 2.0 * a * b, 1.0 - 2.0 * (1.0 - a) * (1.0 - b))
    if op == "hard_mix":
        return (a + b >= 1.0).astype(np.float64)
    return b - a


def color_correct(c, hue_shift=0.0, saturation=1.0, value=1.0, brightness=0.0,
                  contrast=1.0, gain=1.0, gamma=1.0):
    """
    Color Correction. The docs give neither order nor formulas; here:
        HSV: hue + Hue Shift (degrees), saturation * Saturation, value * Value, value + Brightness
        -> RGB * Gain -> contrast (c - 0.5)*Contrast + 0.5 -> Gamma: c^(1/Gamma) (>1 brightens)
    With all defaults the input is returned unchanged (no HSV round trip, so float error can't flip bits).
    """
    if (hue_shift, saturation, value, brightness) != (0.0, 1.0, 1.0, 0.0):
        hsv = _hsv(c)
        hsv[:, 0] = hsv[:, 0] + float(hue_shift) / 360.0
        hsv[:, 1] = np.clip(hsv[:, 1] * float(saturation), 0.0, 1.0)
        hsv[:, 2] = hsv[:, 2] * float(value) + float(brightness)
        c = _rgb(hsv)
    if gain != 1.0:
        c = c * float(gain)
    if contrast != 1.0:
        c = (c - 0.5) * float(contrast) + 0.5
    if gamma != 1.0:
        c = np.sign(c) * np.abs(c) ** (1.0 / max(float(gamma), 1e-6))
    return c


def _scalar_attr(geo, cls, nm, what):
    a = geo.get(cls, str(nm or "").strip()) if str(nm or "").strip() else None
    if a is None or is_string(a):
        have = sorted(geo.attribs[cls].keys())
        raise KeyError(f"{what}: {cls} has no numeric attribute '{nm}'. Existing: {have or '(none)'}")
    return a[:, 0].astype(np.float64)


def _fit01(t, auto, lo, hi, sel):
    """With Compute Range on, takes min / max of the selected elements; a zero-width range gives all 0 (the left end of the ramp)."""
    if auto:
        s = t[sel] if sel.any() else t
        lo, hi = float(s.min()), float(s.max())
    lo, hi = float(lo), float(hi)
    # No 0..1 clamp here: the subsequent ramp.apply takes end values anyway
    return (t - lo) / (hi - lo) if hi - lo > 1e-12 else np.zeros_like(t)


def adjust_color(geo, name="Cd", cls=POINT, group="",
                 blend_mode="constant", blend=1.0, blend_attrib="",
                 delete_others=False, overwrite_initial=False,
                 initial_from="constant", initial_color=(1.0, 1.0, 1.0),
                 initial_attrib="",
                 adjust_value=True, operation="set_always", pattern="constant",
                 color=(1.0, 1.0, 1.0), range_values="min_max", color_space="rgb",
                 min_color=(0.0, 0.0, 0.0), max_color=(1.0, 1.0, 1.0),
                 color_ramp="0:0,0,0 1:1,1,1", color_scheme_="custom",
                 scheme_color=(1.0, 0.0, 0.0), scheme_distance=30.0,
                 color_list="1 0 0\n0 1 0\n0 0 1",
                 adjust_attrib="", source_attrib="", bbox_dir=(0.0, 1.0, 0.0),
                 compute_range=True, source_min=0.0, source_max=1.0,
                 rand_by="element_number", custom_attrib="id", seed=0, noise=None,
                 hue_shift=0.0, saturation=1.0, value=1.0, brightness=0.0,
                 contrast=1.0, gain=1.0, gamma=1.0,
                 use_minimum=False, minimum=0.0, use_maximum=False, maximum=1.0,
                 complement=False):
    """
    Attribute Adjust Color. Order: Pre-Process -> adjustment value (+) original colour (Operation) ->
    Color Correction -> Post-Process (clamp, complement) -> Blend back with the input.
    Blend comes last so that 0 really means "nothing was done" (including correction and post-processing).
    """
    if geo is None:
        return Geometry()
    _check(cls, CLASSES, "Attribute Class")
    _check(pattern, COLOR_PATTERNS, "Pattern Type")
    _check(range_values, COLOR_RANGES, "Range Values")
    _check(color_space, COLOR_SPACES, "Color Space")
    _check(initial_from, COLOR_INITIAL, "Initial Color From")
    nm = str(name or "").strip()
    if not nm:
        raise ValueError("Attribute Name is empty.")
    n = geo.count(cls)
    if n == 0:
        return geo.copy()
    cur = geo.get(cls, nm)
    if cur is not None and (is_string(cur) or cur.shape[1] != 3):
        raise ValueError(f"'{nm}' is not a 3-component numeric attribute; Attribute Adjust Color only handles colours.")
    existed = cur is not None
    orig = cur.astype(np.float64) if existed else np.zeros((n, 3))
    dt = cur.dtype if existed else np.dtype(np.float32)

    base = orig.copy()
    if overwrite_initial:
        if initial_from == "constant":
            base = np.tile(np.asarray(initial_color, np.float64), (n, 1))
        elif initial_from == "color_attribute":
            base = _vec_attr(geo, cls, initial_attrib, "Initial Color From")
        else:
            base = np.repeat(_scalar_attr(geo, cls, initial_attrib, "Initial Color From")[:, None], 3, 1)
        existed = True

    sel = resolve(geo, cls, group)
    out = base
    if adjust_value:
        keys = (element_keys(geo, cls, rand_by, custom_attrib)
                if pattern in ("random", "noise") else None)
        nz = noise or NoiseSpec()
        if pattern == "constant":
            adj = np.tile(np.asarray(color, np.float64), (n, 1))
        elif pattern == "color_attribute":
            adj = _vec_attr(geo, cls, adjust_attrib, "Adjustment Attribute")
        elif pattern in ("remap_attribute", "bounding_box"):
            if pattern == "remap_attribute":
                t = _scalar_attr(geo, cls, source_attrib, "Source Attribute")
            else:
                P = _an._sample_positions(geo, cls, "P")
                if len(P) == 1 and n > 1:
                    P = np.repeat(P, n, axis=0)
                dvec = np.asarray(bbox_dir, np.float64)
                t = P @ (dvec / max(np.linalg.norm(dvec), 1e-12))
            t = _fit01(t, compute_range, source_min, source_max, sel)
            pos, val = _ramp.parse(color_ramp, 3)
            adj = _ramp.apply(t, pos, val, "linear")
        else:
            def u_at(c):
                return (rand_u(keys, seed, 401 + 17 * c) if pattern == "random"
                        else nz.u(geo, cls, seed, 7919 * c))
            if range_values == "min_max":
                u3 = np.stack([u_at(c) for c in range(3)], 1)
                lo = np.asarray(min_color, np.float64)[None, :]
                hi = np.asarray(max_color, np.float64)[None, :]
                adj = lo + (hi - lo) * u3
                if color_space == "hsv":
                    adj = _rgb(adj)
            elif range_values == "color_ramp":
                pos, val = _ramp.parse(color_ramp, 3)
                adj = _ramp.apply(u_at(0), pos, val, "linear")
            else:
                if color_scheme_ == "custom":
                    tab = parse_value_list(color_list)
                    for vals, _ in tab:
                        if len(vals) != 3:
                            raise ValueError("Each line of the colour table needs 3 numbers (r g b).")
                    cols = np.stack([v for v, _ in tab])
                    w = [wt for _, wt in tab]
                else:
                    cols = color_scheme(color_scheme_, scheme_color, scheme_distance)
                    w = [1.0] * len(cols)
                idx = pick_specific(u_at(0), [(np.array([float(i)]), wt)
                                              for i, wt in enumerate(w)]).astype(np.int64)
                adj = cols[idx]
        out = color_combine(operation, base, adj, existed)

    out = color_correct(out, hue_shift, saturation, value, brightness, contrast, gain, gamma)
    if use_minimum:
        out = np.maximum(out, float(minimum))
    if use_maximum:
        out = np.minimum(out, float(maximum))
    if complement:
        out = 1.0 - out
    w = blend_weights(geo, cls, n, blend_mode, blend, blend_attrib)
    out = orig + (out - orig) * w[:, None]
    out = np.where(sel[:, None], out, orig)

    g = geo.copy()
    if delete_others:
        # Point colour overrides primitive colour (per the docs), so only "deleting same-named colours on other classes" makes the one written here take effect
        for c in CLASSES:
            if c != cls:
                g.remove(c, nm)
    g.set(cls, nm, out.astype(dt), owned=True)
    return g
