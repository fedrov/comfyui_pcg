"""
Attribute Adjust Float / Integer / Vector / Color -- Houdini-semantics version (pcg100 s6).

PCG_AttribAdjust (attribadjust.py) is this plugin's own "four-section pipeline + text operation stack", which merges
Houdini's three Adjust nodes into one; its Initialize menu is not the same thing as Houdini's
Operation x Pattern Type (no Set Initial, no Range Values,
no discrete value table). Bolting a dozen mode parameters onto it would make the panel unmanageable, and two semantics side by side
("Initialize=random" and "Pattern=Random" appearing together) would only confuse people. So here
**four separate nodes** are added, one per Houdini node, and the original node is left alone.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Shared skeleton: adjustment value (+) original value -> blend -> post-processing
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    adjustment   generated by Pattern Type: Constant / Random / Noise / Attribute
                 Random and Noise first produce a 0..1 u, then map it to the value range per Range Values
    ⊕        Operation:Set Initial / Set Always / Add / Subtract / Multiply /
             Minimum / Maximum (Color and Vector each have their own extensions)
    blend    Blend (constant or attribute), 0 = original value, 1 = adjusted
    post     Minimum / Maximum clamping (each node's extra items: see the respective functions)

When the attribute did not exist before, per the Houdini docs "all operations have the same effect" -- the adjustment value is written directly,
and Set Initial writes too (which is exactly the point of it).

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Where u comes from, and why Noise is not uniformly distributed
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Random's u is attribrandomize._rand01 (seeded by element number or a custom attribute), strictly uniform.
Noise's u is fractal_noise's [-1,1] mapped linearly to [0,1] -- noise values naturally cluster in the middle,
so values from Noise + Min/Max also cluster in the middle of the range and rarely reach the ends. The Houdini docs don't say whether
the noise is "flattened" into a uniform distribution; here it is **not flattened**, consistent with the Attribute Noise node.
"""
