def _check(val, choices, what):
    if val not in choices:
        raise ValueError(f"{what} must be one of {choices}, got '{val}'.")


# ══════════════════════════════════════════════════════════ discrete value table
def parse_value_list(text):
    """
    Houdini's Number of Values multiparm, written one group per line (ComfyUI has no multiparm):

        3                 Value Type = Constant, a single value
        1 2 5  w=2        Value Type = List of Values, weight 2
        0-10:2; 20        Value List syntax: min-max:step, separated by spaces / commas / semicolons
        # comment

    Returns [(values ndarray, weight)].

    **The weight is the probability of "this group" being chosen**; the values within a group then split it evenly -- the Houdini docs say
    "each group's probability of being chosen is proportional to its Weight", and an expanded list "shares the same Weight". The docs
    don't settle between the two readings (groups by weight vs each expanded value by its own weight); here the former is used: with a group
    0-100 and a group 500 both of weight 1, 500 appears half the time, not 1/52 of it.
    """
    out = []
    for i, raw in enumerate(str(text or "").splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        w = 1.0
        m = re.search(r"\bw\s*=\s*(\S+)\s*$", line)
        if m:
            try:
                w = float(m.group(1))
            except ValueError:
                raise ValueError(f"Value table line {i}: weight '{m.group(1)}' is not a number.")
            line = line[:m.start()].strip()
        if w < 0:
            raise ValueError(f"Value table line {i}: weight cannot be negative.")
        vals = []
        for tok in re.split(r"[\s,;]+", line):
            if not tok:
                continue
            r = _LIST_RANGE.match(tok)
            if r:
                a, b = float(r.group(1)), float(r.group(2))
                st = abs(float(r.group(3))) if r.group(3) else 1.0
                if st <= 0:
                    raise ValueError(f"Value table line {i}: step of '{tok}' is 0.")
                k = int(np.floor(abs(b - a) / st + 1e-9))
                vals.extend((a + np.sign(b - a) * st * np.arange(k + 1)).tolist())
                continue
            try:
                vals.append(float(tok))
            except ValueError:
                raise ValueError(f"Value table line {i}: '{tok}' is neither a number nor "
                                 f"min-max:step.\n  {raw.strip()}")
        if not vals:
            raise ValueError(f"Value table line {i}: has a weight but no values.")
        out.append((np.asarray(vals, np.float64), w))
    if not out:
        raise ValueError("Range Values = Specific Values, but the value table is empty.")
    if sum(w for _, w in out) <= 0:
        raise ValueError("All weights in the value table are 0.")
    return out


def pick_specific(u, table):
    """
    u in [0,1) -> value. First picks a group by the cumulative weight distribution, then picks a value evenly with the remaining part of u within the group.

    Uses **one** u rather than two random numbers: in Noise mode u is a continuous field, the same u gives
    the same value, so discrete values appear in patches (what the Houdini docs mean by "Pattern Type decides how values are picked").
    """
    w = np.array([wt for _, wt in table], np.float64)
    c = np.cumsum(w) / w.sum()
    u = np.clip(np.asarray(u, np.float64), 0.0, np.nextafter(1.0, 0.0))
    gi = np.minimum(np.searchsorted(c, u, side="right"), len(table) - 1)
    lo = np.where(gi > 0, c[np.maximum(gi - 1, 0)], 0.0)
    span = np.maximum(c[gi] - lo, 1e-300)
    r = np.clip((u - lo) / span, 0.0, np.nextafter(1.0, 0.0))
    out = np.empty(len(u))
    for k, (vals, _) in enumerate(table):
        m = gi == k
        if m.any():
            out[m] = vals[np.minimum((r[m] * len(vals)).astype(np.int64),
                                     len(vals) - 1)]
    return out


# ══════════════════════════════════════════════════════════ sources of u
def element_keys(geo, cls, rand_by="element_number", custom_attrib="id"):
    _check(rand_by, RAND_BY, "Randomization By")
    n = geo.count(cls)
    if rand_by == "element_number":
        return np.arange(n, dtype=np.float64)
    nm = str(custom_attrib or "").strip()
    a = geo.get(cls, nm) if nm else None
    if a is None or is_string(a):
        have = sorted(geo.attribs[cls].keys())
        raise KeyError(f"Randomization By = Custom Attribute, but {cls} has no numeric attribute "
                       f"'{nm}'. Existing: {have or '(none)'}")
    return a[:, 0].astype(np.float64)


def rand_u(keys, seed, salt):
    from .attribrandomize import _rand01
    return _rand01(keys, int(seed), int(salt))


class NoiseSpec:
    """Parameter bundle of the Noise Pattern tab. Shared by all four nodes, to keep function signatures short."""
    def __init__(self, noise_type="perlin", location="P", element_size=1.0,
                 element_scale=(1.0, 1.0, 1.0), offset=(0.0, 0.0, 0.0),
                 fractal="none", octaves=3, lacunarity=2.0, roughness=0.5):
        _check(noise_type, NOISE_TYPES, "Noise Type")
        _check(fractal, FRACTALS, "Fractal Type")
        self.noise_type = noise_type
        self.location = location
        self.element_size = float(element_size)
        self.element_scale = tuple(float(x) for x in element_scale)
        self.offset = tuple(float(x) for x in offset)
        self.fractal = fractal
        self.octaves = int(octaves)
        self.lacunarity = float(lacunarity)
        self.roughness = float(roughness)

    def sample(self, geo, cls, seed, salt=0):
        """(N,) noise in [-1,1]. Sample position = (position + Offset) / (Element Size * Scale)."""
        n = geo.count(cls)
        Q = _an._sample_positions(geo, cls, self.location)
        if len(Q) == 1 and n > 1:
            Q = np.repeat(Q, n, axis=0)
        es = self.element_size * np.asarray(self.element_scale, np.float64)
        es = np.where(np.abs(es) < 1e-9, 1e-9, es)
        S = (Q + np.asarray(self.offset)[None, :]) / es[None, :]
        return _an.fractal_noise(S, self.noise_type, _FRACTAL_MAP[self.fractal],
                                 self.octaves, self.lacunarity, self.roughness,
                                 int(seed) + int(salt))

    def u(self, geo, cls, seed, salt=0):
        return np.clip(0.5 * (self.sample(geo, cls, seed, salt) + 1.0), 0.0, 1.0)


# ══════════════════════════════════════════════════════════ scalar values
def range_bounds(mode, min_value, max_value, middle_value, range_length,
                 integer=False):
    """Range Values -> (lo, hi). In Middle +/- Range Length the **half-width = half the length**
    (Attribute Adjust's definition; Attribute Noise's mode of the same name is the full width, don't mix them up)."""
    _check(mode, RANGES, "Range Values")
    if mode == "min_max":
        lo, hi = float(min_value), float(max_value)
    elif mode == "min_range":
        lo = float(min_value)
        hi = lo + float(range_length)
    elif mode == "middle_range":
        h = 0.5 * float(range_length)
        lo, hi = float(middle_value) - h, float(middle_value) + h
        if integer:
            # Integer docs: centre 0, length 2 -> -1..1; with length 3, +/-1.5 is not reachable, so shrink inwards
            lo, hi = float(np.ceil(lo - 1e-9)), float(np.floor(hi + 1e-9))
    else:
        raise ValueError("Specific Values has no range.")
    return lo, hi


class ScalarSpec:
    """How a scalar adjustment value is picked: Range Values / Distribution / Outlier / Stepping / value table."""
    def __init__(self, range_values="min_max", min_value=0.0, max_value=1.0,
                 middle_value=0.5, range_length=1.0, distribution="uniform",
                 remap_ramp="0:0 1:1", outlier_percent=10.0, outlier_range=1.0,
                 outlier_mode="additive", outlier_extent="above_max",
                 outlier_seed=0, use_stepping=False, step_size=1.0,
                 value_list="0 1", integer=False):
        _check(range_values, RANGES, "Range Values")
        _check(distribution, DISTRIBUTIONS, "Value Distribution")
        _check(outlier_mode, OUTLIER_MODES, "Outlier Range Mode")
        _check(outlier_extent, OUTLIER_EXTENTS, "Outlier Extent")
        self.range_values = range_values
        self.bounds = None if range_values == "specific" else range_bounds(
            range_values, min_value, max_value, middle_value, range_length,
            integer)
        self.table = (parse_value_list(value_list)
                      if range_values == "specific" else None)
        self.distribution = distribution
        self.remap_ramp = remap_ramp
        self.outlier_percent = float(outlier_percent)
        self.outlier_range = float(outlier_range)
        self.outlier_mode = outlier_mode
        self.outlier_extent = outlier_extent
        self.outlier_seed = int(outlier_seed)
        self.use_stepping = bool(use_stepping)
        self.step_size = float(step_size)
        self.integer = bool(integer)

    def values(self, u, keys):
        """u (N,) in [0,1] -> (values (N,), outlier mask (N,) bool)."""
        u = np.asarray(u, np.float64)
        n = len(u)
        if self.table is not None:
            return pick_specific(u, self.table), np.zeros(n, bool)
        lo, hi = self.bounds
        t = u
        if self.distribution == "uniform_remap":
            # Docs: "first generates uniform values in -1..1, then maps them to a custom range through the Remap Ramp".
            # The ramp's horizontal axis is u (left = Min, right = Max), the vertical 0..1 is then stretched to the range --
            # the same reading as Attribute Noise's Remap Ramp
            pos, val = _ramp.parse(self.remap_ramp, 1)
            t = np.clip(_ramp.apply(u, pos, val, "linear")[:, 0], 0.0, 1.0)
        out = self._fit(t, lo, hi)
        outl = np.zeros(n, bool)
        if self.distribution == "uniform_outliers":
            outl, ov = self._outliers(keys, lo, hi)
            out = np.where(outl, ov, out)
        return out, outl

    def _fit(self, t, lo, hi):
        """t in [0,1] -> value in the range; for integers / with Stepping on, discrete grid values (both ends included)."""
        t = np.clip(t, 0.0, np.nextafter(1.0, 0.0))
        step = abs(self.step_size) if self.use_stepping else (
            1.0 if self.integer else 0.0)
        if step <= 0:
            return lo + (hi - lo) * t
        # Integer docs: range 1..9, step 2 -> 1 3 5 7 9. The grid starts from Min, not from 0;
        # "split into m+1 equal parts and take the k-th" rather than round, so ends and middle values are equally likely
        # For integers lo / hi are already integers: Min / Max are INT controls, and Middle +/- was
        # shrunk in range_bounds()
        m = max(int(np.floor((hi - lo) / step + 1e-9)), 0)
        k = np.minimum(np.floor(t * (m + 1)), m)
        return lo + k * step

    def _outliers(self, keys, lo, hi):
        """
        Uniform with Outliers: Outlier Percent% of the elements land **outside** the original range.
        Additive: extension band = Outlier Range; Multiplicative: extension band =
        (Outlier Range - 1) * range length (Range 2 = extend outward by one more range length).
        The docs only say "added to the ends / multiplied onto the ends"; multiplying the end values directly would leave the lower end of
        range [0,1] stuck at 0 forever, so it is interpreted via the range length; this is recorded in the notes.
        """
        r = rand_u(keys, self.outlier_seed, 7717)
        outl = r < self.outlier_percent / 100.0
        L = hi - lo
        ext = (self.outlier_range if self.outlier_mode == "additive"
               else (self.outlier_range - 1.0) * L)
        ext = max(ext, 0.0)
        s = rand_u(keys, self.outlier_seed, 7723)
        if self.outlier_extent == "above_max":
            below = np.zeros(len(r), bool)
        elif self.outlier_extent == "below_min":
            below = np.ones(len(r), bool)
        else:
            below = rand_u(keys, self.outlier_seed, 7727) < 0.5
        v = np.where(below, lo - ext * s, hi + ext * s)
        if self.integer:
            # Outliers must be integers too, and at least 1 outside the range (otherwise ceil back onto the end would not count as an outlier)
            v = np.where(below, np.minimum(np.floor(v), lo - 1),
                         np.maximum(np.ceil(v), hi + 1))
        elif self.use_stepping and self.step_size > 0:
            st = abs(self.step_size)
            v = lo + np.round((v - lo) / st) * st
        return outl, v


# ══════════════════════════════════════════════════════════ write-back helpers
def split_component(name):
    """'v.x' / 'v[1]' / 'Cd.g' -> ('v', 0). No component suffix -> (name, None)."""
    nm = str(name or "").strip()
    m = _COMP.match(nm)
    if not m:
        return nm, None
    return m.group(1), (_COMP_IDX[m.group(2)] if m.group(2) is not None
                        else int(m.group(3)))


def blend_weights(geo, cls, n, blend_mode, blend, blend_attrib):
    _check(blend_mode, BLEND_MODES, "Blend")
    if blend_mode == "constant":
        return np.full(n, float(np.clip(blend, 0.0, 1.0)))
    nm = str(blend_attrib or "").strip()
    a = geo.get(cls, nm) if nm else None
    if a is None or is_string(a):
        have = sorted(geo.attribs[cls].keys())
        raise KeyError(f"Blend = Use Attribute, but {cls} has no numeric attribute '{nm}'. "
                       f"Existing: {have or '(none)'}")
    return np.clip(a[:, 0].astype(np.float64), 0.0, 1.0)


def combine(op, base, adj, existed):
    """Operation: base (+) adj. If the attribute did not exist before, always just take the adjustment value (per the docs)."""
    _check(op, OPERATIONS, "Operation")
    if not existed or op == "set_always":
        return adj
    if op == "set_initial":
        return base
    if op == "add":
        return base + adj
    if op == "subtract":
        return base - adj
    if op == "multiply":
        return base * adj
    if op == "minimum":
        return np.minimum(base, adj)
    return np.maximum(base, adj)


# ══════════════════════════════════════════════════════════ Float / Integer
def adjust_scalar(geo, name="pscale", cls=POINT, group="", integer=False,
                  blend_mode="constant", blend=1.0, blend_attrib="",
                  adjust_value=True, operation="set_always", pattern="constant",
                  constant_value=0.0, scalar=None,
                  adjust_attrib="", attrib_mode="scale", attrib_scale=1.0,
                  attrib_offset=0.0,
                  rand_by="element_number", custom_attrib="id", seed=0,
                  noise=None,
                  use_minimum=False, minimum=0.0, use_maximum=False,
                  maximum=1.0, outlier_attrib=""):
    """
    Attribute Adjust Float / Integer. scalar is a ScalarSpec, noise is a NoiseSpec.

    With a component suffix in the name (v.x, v[1]) only that component is changed; if the name points to a vector attribute without a component,
    per the Houdini docs it is the **length** that is adjusted (direction unchanged, zero vectors stay zero).
    """
    if geo is None:
        return Geometry()
    _check(cls, CLASSES, "Attribute Class")
    _check(pattern, PATTERNS, "Pattern Type")
    _check(attrib_mode, ATTRIB_MODES, "Attribute Adjustment")
    base_nm, comp = split_component(name)
    if not base_nm:
        raise ValueError("Attribute Name is empty.")
    n = geo.count(cls)
    if n == 0:
        return geo.copy()

    cur = geo.get(cls, base_nm)
    if cur is not None and is_string(cur):
        raise ValueError(f"'{base_nm}' is a string attribute; Attribute Adjust only handles numeric values.")
    existed = cur is not None
    if existed:
        full = cur.astype(np.float64)
        if comp is not None and comp >= full.shape[1]:
            raise ValueError(f"'{base_nm}' has only {full.shape[1]} components, no [{comp}].")
        dt = cur.dtype
    else:
        C = 1 if comp is None else comp + 1
        full = np.zeros((n, C))
        dt = np.dtype(np.int32) if integer else np.dtype(np.float32)
    length_mode = comp is None and full.shape[1] > 1
    if comp is not None:
        base = full[:, comp].copy()
    elif length_mode:
        base = np.linalg.norm(full, axis=1)
    else:
        base = full[:, 0].copy()

    sel = resolve(geo, cls, group)
    keys = None
    outl = np.zeros(n, bool)
    v = base
    if adjust_value:
        if pattern == "constant":
            adj = np.full(n, float(constant_value))
        elif pattern == "attribute":
            anm, acomp = split_component(adjust_attrib)
            a = geo.get(cls, anm) if anm else None
            if a is None or is_string(a):
                have = sorted(geo.attribs[cls].keys())
                raise KeyError(f"Pattern Type = Attribute, but {cls} has no numeric attribute "
                               f"'{anm}'. Existing: {have or '(none)'}")
            adj = a[:, acomp or 0].astype(np.float64)
            if attrib_mode in ("scale", "both"):
                adj = adj * float(attrib_scale)
            if attrib_mode in ("offset", "both"):
                adj = adj + float(attrib_offset)
        else:
            sc = scalar or ScalarSpec(integer=integer)
            keys = element_keys(geo, cls, rand_by, custom_attrib)
            if pattern == "random":
                u = rand_u(keys, seed, 401)
            else:
                u = (noise or NoiseSpec()).u(geo, cls, seed, 0)
            adj, outl = sc.values(u, keys)
        v = combine(operation, base, adj, existed)

    if integer:
        v = np.rint(v)
    else:
        w = blend_weights(geo, cls, n, blend_mode, blend, blend_attrib)
        v = base + (v - base) * w
    if use_minimum:
        v = np.maximum(v, float(minimum))
    if use_maximum:
        v = np.minimum(v, float(maximum))
    v = np.where(sel, v, base)

    if comp is not None:
        out = full.copy()
        out[:, comp] = v
    elif length_mode:
        # Zero vectors: L becomes 1 to avoid dividing by zero; full itself is 0 so the product is still 0 -- the docs say adjusting
        # the length of a zero vector keeps it zero, no special case needed
        L = np.where(base < 1e-12, 1.0, base)
        out = full * (v / L)[:, None]
    else:
        out = v[:, None]
    g = geo.copy()
    g.set(cls, base_nm, (np.rint(out) if dt.kind in "iub" else out).astype(dt),
          owned=True)
    onm = str(outlier_attrib or "").strip()
    if onm:
        g.set(cls, onm, (outl & sel).astype(np.int32)[:, None], owned=True)
    return g


