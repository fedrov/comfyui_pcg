def _vec(prefix, label, kind="vector", comps="xyz", **extra):
    """Row spec for prefix_x / _y / _z (or _r / _g / _b), set on the first member."""
    members = [f"{prefix}_{c}" for c in comps]
    d = {"row": {"kind": kind, "members": members, "label": label}}
    d.update(extra)
    return {members[0]: d}


